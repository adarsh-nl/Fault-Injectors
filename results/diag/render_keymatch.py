#!/usr/bin/env python3
"""Render results/diag/keymatch_raw.json into one markdown file per model.

Pure stdlib, no torch -- safe to run on a login node. The verdict rule is
stated in the output of every file so a reader never has to come back here to
learn what CHEAP or NOT-WORTH-IT meant.
"""
import json
from pathlib import Path

DIAG = Path(__file__).resolve().parent
RAW = DIAG / "keymatch_raw.json"

# Verdict thresholds on "% of official tensors matched exactly by name+shape".
# CHEAP is set high on purpose: a converter is only cheap if the structures
# already correspond and the work is renaming. Anything below MODERATE means
# the two graphs are different graphs and a converter is a reimplementation.
CHEAP, MODERATE = 60.0, 15.0

RULE = f"""\
**Verdict rule.** On `pct_official_exact` = share of official tensors matched
by *both* name and shape:

| verdict | rule | meaning |
|---|---|---|
| `CHEAP` | >= {CHEAP:.0f}% | structures correspond; a converter is a rename table |
| `MODERATE` | {MODERATE:.0f}-{CHEAP:.0f}% | shapes largely align, module layout differs |
| `NOT-WORTH-IT` | < {MODERATE:.0f}% | different graphs; a "converter" would be a reimplementation |
| `BLOCKED-BY-IMPORT` | reimpl would not construct | measurement impossible, cause recorded |
| `NO-CHECKPOINT` | no released weights exist | nothing to convert |

`pct_official_shape_recoverable_upper_bound` additionally counts official
tensors for which *some* unclaimed reimpl tensor has an identical shape. It
ignores whether such a pairing would be semantically correct, so it is a
strict **upper bound** on what any rename-only converter could ever recover.
"""


def verdict(entry):
    if entry.get("official", {}).get("status") == "ABSENT":
        return "NO-CHECKPOINT"
    if entry.get("reimpl", {}).get("status") != "OK":
        return "BLOCKED-BY-IMPORT"
    if entry.get("official", {}).get("status") != "OK":
        return "BLOCKED-OFFICIAL-LOAD"
    pct = entry["keymatch"]["pct_official_exact"]
    if pct >= CHEAP:
        return "CHEAP"
    if pct >= MODERATE:
        return "MODERATE"
    return "NOT-WORTH-IT"


def render(name, entry):
    v = verdict(entry)
    L = [f"# Keymatch: {name}", "",
         f"**Verdict: `{v}`**", "",
         "Generated by `results/diag/render_keymatch.py` from "
         "`keymatch_raw.json`, which is produced by "
         "`results/diag/keymatch_diag.sbatch`. Read-only measurement: no "
         "converter is written and no weights are modified.", ""]

    off, re_ = entry.get("official", {}), entry.get("reimpl", {})
    L += ["## Sources", "",
          "| side | status | tensors | source |", "|---|---|---|---|",
          f"| official | `{off.get('status')}` | {off.get('tensors', '-')} | "
          f"`{off.get('path', off.get('reason', '-'))}` |",
          f"| reimpl | `{re_.get('status')}` | {re_.get('tensors', '-')} | "
          f"`{re_.get('pkg', '-')} {' '.join(re_.get('overrides', []))}` |", ""]

    if off.get("status") == "ABSENT":
        L += [f"No released weights: {off.get('reason')}. There is nothing to "
              "convert; this model's only path to a number is "
              "train-under-the-paper's-protocol.", "", RULE]
        return "\n".join(L)

    if re_.get("status") != "OK":
        L += ["## Reimplementation would not construct", "",
              "The measurement could not be taken. Traceback:", "",
              "```", re_.get("traceback", "").strip(), "```", "", RULE]
        return "\n".join(L)

    if off.get("status") != "OK":
        L += ["## Official checkpoint would not load", "", "```",
              off.get("traceback", "").strip(), "```", "", RULE]
        return "\n".join(L)

    k = entry["keymatch"]
    L += ["## Counts", "",
          "| category | count | % of official |", "|---|---:|---:|",
          f"| (a) exact name **and** shape | {k['exact_name_and_shape']} | "
          f"{k['pct_official_exact']}% |",
          f"| (b) name matches, shape differs | "
          f"{k['name_match_shape_differs']} | "
          f"{round(100 * k['name_match_shape_differs'] / max(k['official_tensors'], 1), 2)}% |",
          f"| (c) official-only (no such reimpl key) | {k['official_only']} | "
          f"{round(100 * k['official_only'] / max(k['official_tensors'], 1), 2)}% |",
          f"| (d) reimpl-only (no such official key) | {k['reimpl_only']} | "
          f"- (of {k['reimpl_tensors']} reimpl) |", "",
          f"- official tensors: **{k['official_tensors']}**",
          f"- reimpl tensors: **{k['reimpl_tensors']}**",
          f"- shape-pairable among the unmatched: "
          f"{k['shape_pairable_among_unmatched']}",
          f"- **upper bound** on rename-only recovery: "
          f"**{k['pct_official_shape_recoverable_upper_bound']}%**", ""]

    if k["examples_exact"]:
        L += ["## (a) Examples: exact name and shape", "", "```"]
        L += k["examples_exact"] + ["```", ""]
    else:
        L += ["## (a) Examples: exact name and shape", "",
              "**None.** Not one official tensor name also exists in the "
              "reimplementation at the same shape.", ""]

    if k["examples_name_match_shape_differs"]:
        L += ["## (b) Examples: name matches, shape differs", "",
              "| key | official | reimpl |", "|---|---|---|"]
        L += [f"| `{e['key']}` | `{e['official']}` | `{e['reimpl']}` |"
              for e in k["examples_name_match_shape_differs"]]
        L += [""]

    L += ["## (c) Examples: official-only", "", "```"]
    L += k["examples_official_only"] + ["```", ""]
    L += ["## (d) Examples: reimpl-only", "", "```"]
    L += k["examples_reimpl_only"] + ["```", ""]

    L += ["## Top-level module layout", "",
          "How each side groups its tensors under its first two name "
          "components. Divergence here is the structural story; divergence in "
          "the leaf names alone would be a rename job.", "",
          "| official prefix | n | | reimpl prefix | n |",
          "|---|---:|---|---|---:|"]
    op, rp = k["official_prefixes"], k["reimpl_prefixes"]
    for i in range(max(len(op), len(rp))):
        a = f"`{op[i][0]}` | {op[i][1]}" if i < len(op) else " | "
        b = f"`{rp[i][0]}` | {rp[i][1]}" if i < len(rp) else " | "
        L.append(f"| {a} | | {b} |")
    L += ["", RULE]
    return "\n".join(L)


def main():
    raw = json.loads(RAW.read_text())
    summary = []
    for name, entry in raw.items():
        (DIAG / f"{name}_keymatch.md").write_text(render(name, entry) + "\n")
        v = verdict(entry)
        km = entry.get("keymatch") or {}
        summary.append((name, v, km.get("pct_official_exact"),
                        km.get("pct_official_shape_recoverable_upper_bound"),
                        entry.get("official", {}).get("tensors"),
                        entry.get("reimpl", {}).get("tensors")))
        print(f"{name:28s} {v:22s} exact={km.get('pct_official_exact')}%  "
              f"upper={km.get('pct_official_shape_recoverable_upper_bound')}%  "
              f"off={entry.get('official', {}).get('tensors')} "
              f"reimpl={entry.get('reimpl', {}).get('tensors')}")

    lines = ["# Keymatch summary", "",
             "| model | verdict | exact name+shape | rename-only upper bound "
             "| official tensors | reimpl tensors |",
             "|---|---|---:|---:|---:|---:|"]
    for n, v, p, u, o, r in summary:
        lines.append(f"| [{n}]({n}_keymatch.md) | `{v}` | "
                     f"{p if p is not None else '-'}% | "
                     f"{u if u is not None else '-'}% | {o or '-'} | {r or '-'} |")
    lines += ["", RULE]
    (DIAG / "keymatch_summary.md").write_text("\n".join(lines) + "\n")
    print("WROTE keymatch_summary.md")


if __name__ == "__main__":
    main()
